// Generate the agent-facing catalog (skill/references/catalog.md) and the quick-pick table in SKILL.md.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const START = '<!-- catalog:start -->';
const END = '<!-- catalog:end -->';

const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ');

function quickTable(styles) {
  const rows = styles.map((s) =>
    `| \`${s.id}\` | ${cell(s.best_for.en[0])} | ${s.tools.primary} | ${s.tags.aspect.join(', ')} |`,
  );
  return ['| Style | Pick it for | Tool | Aspect |', '|---|---|---|---|', ...rows].join('\n');
}

function styleSection(s) {
  const alts = s.tools.alternatives.length ? ` (alt: ${s.tools.alternatives.join(', ')})` : '';
  const variants = s.variants?.length
    ? s.variants.map((v) => `\`${v.id}\` - ${v.en}`).join('; ')
    : 'none';
  return [
    `## ${s.id} - ${s.name.en}`,
    '',
    s.tagline.en,
    '',
    `- **Best for**: ${s.best_for.en.join('; ')}`,
    `- **Avoid when**: ${s.avoid_when.en.join('; ')}`,
    `- **Tool**: ${s.tools.primary}${alts}. ${s.tools.why.en}`,
    `- **Format**: ${s.tags.aspect.join(', ')}; ${s.duration}; difficulty ${s.difficulty}/3`,
    `- **Needs from user**: ${s.tags.needs.join(', ') || 'nothing'}`,
    `- **Audio**: ${s.tags.audio.join(', ')}`,
    `- **Variants**: ${variants}`,
    `- **Evidence**: ${s.evidence.length} public examples (${s.evidence_strength})`,
    `- **Recipe**: \`styles/${s.id}.md\``,
    '',
  ].join('\n');
}

export async function writeCatalog(root, styles) {
  const body = [
    '# Style catalog',
    '',
    '<!-- Generated by scripts/build.mjs from data/styles/*.yaml. Do not edit by hand. -->',
    '',
    'Each style below is backed by at least two independent public examples of agent-made, code-rendered video.',
    'Pick one, then read its recipe in `styles/<id>.md`.',
    '',
    quickTable(styles),
    '',
    ...styles.map(styleSection),
  ].join('\n');
  await writeFile(path.join(root, 'skill', 'references', 'catalog.md'), body);
}

/** Replace the content between two marker comments in a file. */
async function injectBetween(filePath, startMarker, endMarker, content) {
  const text = await readFile(filePath, 'utf8');
  const start = text.indexOf(startMarker);
  const end = text.indexOf(endMarker);
  if (start === -1 || end === -1) throw new Error(`${filePath} is missing the ${startMarker} markers`);
  const next = `${text.slice(0, start + startMarker.length)}\n${content}\n${text.slice(end)}`;
  if (next !== text) await writeFile(filePath, next);
}

export async function injectSkillTable(root, styles) {
  await injectBetween(path.join(root, 'skill', 'SKILL.md'), START, END, quickTable(styles));
}

function readmeTable(styles, lang) {
  const head = lang === 'zh'
    ? ['| 风格 | 适合 | 工具 | 预览 |', '|---|---|---|---|']
    : ['| Style | Best for | Tool | Preview |', '|---|---|---|---|'];
  const pending = lang === 'zh' ? '待渲染' : 'pending';
  const watch = lang === 'zh' ? '观看' : 'watch';
  const rows = styles.map((s) => {
    const preview = s.hasPreview ? `[${watch}](previews/${s.id}.mp4)` : pending;
    return `| [${cell(s.name[lang])}](skill/references/styles/${s.id}.md) | ${cell(s.best_for[lang][0])} | ${s.tools.primary} | ${preview} |`;
  });
  return [...head, ...rows].join('\n');
}

export async function injectReadmeTables(root, styles) {
  const markers = ['<!-- styles:start -->', '<!-- styles:end -->'];
  await injectBetween(path.join(root, 'README.md'), ...markers, readmeTable(styles, 'en'));
  await injectBetween(path.join(root, 'README.zh-CN.md'), ...markers, readmeTable(styles, 'zh'));
}
