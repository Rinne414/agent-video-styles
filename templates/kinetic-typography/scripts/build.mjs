// Generates index.html from content.json. Run: node scripts/build.mjs
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const c = JSON.parse(readFileSync(join(root, "content.json"), "utf8"));
const { width: W, height: H, fps: FPS, bpm: BPM, offsetFrames, totalBeats } = c.video;
// HyperFrames blacks out the right-most 8 px when width is not a multiple of 16: compose wider, crop in `pnpm run render`.
const CW = Math.ceil(W / 16) * 16;
const { motion: M, palette: P, font: F, poster, phraseTiming: PT } = c;

// Beat grid: always computed from the beat index, never accumulated.
const beatFrame = (i) => Math.round(offsetFrames + ((i * 60) / BPM) * FPS);
const sec = (frame) => +(frame / FPS).toFixed(5);
const TOTAL = beatFrame(totalBeats);

mkdirSync(join(root, "fonts"), { recursive: true });
copyFileSync(join(root, "node_modules/@fontsource/anton/files/anton-latin-400-normal.woff2"), join(root, "fonts/anton.woff2"));

const upper = (s) => s.toUpperCase();
const clipInset = {
  left: ["inset(0 100% 0 0)", "inset(0 0% 0 0)"],
  right: ["inset(0 0 0 100%)", "inset(0 0 0 0%)"],
  top: ["inset(0 0 100% 0)", "inset(0% 0 0 0)"],
  bottom: ["inset(100% 0 0 0)", "inset(0 0 0% 0)"],
};

let html = "";
const js = [];
const slam = (sel, f) =>
  js.push(`tl.fromTo("${sel}", {opacity:0, scale:${M.slamFrom}}, {opacity:1, scale:1, duration:${sec(M.slamFrames)}, ease:"expo.out"}, ${sec(f)});`);
const cut = (sel, f) => js.push(`tl.set("${sel}", {opacity:0}, ${sec(f)});`);
const pulse = (sel, f) =>
  js.push(`tl.fromTo("${sel}", {scale:${M.pulseScale}}, {scale:1, duration:${sec(M.pulseFrames)}, ease:"expo.out", immediateRender:false}, ${sec(f)});`);

c.phrases.forEach((p, n) => {
  const s = beatFrame(p.startBeat);
  const e = beatFrame(p.startBeat + PT.beatsPerPhrase);
  const key = p.keyIndex;
  let words = "";
  p.words.forEach((w, i) => {
    const color = i === key ? P[p.accent] : P[p.type];
    words += `<div id="p${n}w${i}" class="word" style="color:${color};font-size:${p.size}px">${upper(w)}</div>`;
  });
  html += `<section id="p${n}" class="scene clip" data-start="${sec(s)}" data-duration="${sec(e - s)}" data-track-index="0" style="background:${P[p.stage]}">${words}</section>\n`;

  const keyStart = beatFrame(p.startBeat + PT.keyWordBeat);
  // first word: lands on the phrase beat, pulses once, hard-cut by the key word
  slam(`#p${n}w0`, s);
  pulse(`#p${n}w0`, beatFrame(p.startBeat + PT.firstWordPulseBeat));
  cut(`#p${n}w0`, keyStart);
  // key word: lands, thumps on every beat, exits just before the next phrase
  slam(`#p${n}w${key}`, keyStart);
  PT.keyPulseBeats.forEach((b) => pulse(`#p${n}w${key}`, beatFrame(p.startBeat + b)));
  js.push(`tl.to("#p${n}w${key}", {opacity:0, scale:${M.exitScale}, duration:${sec(M.exitFrames)}, ease:"power2.in"}, ${sec(e - M.exitFrames)});`);
});

// Poster-color-block finale: one field layer per beat, wiped in over the previous one.
const ps = beatFrame(poster.startBeat);
let layers = "";
poster.fields.forEach((f, i) => {
  const hidden = clipInset[f.wipe][0];
  layers += `<div id="f${i}" class="field" style="background:${P[f.bg]};clip-path:${hidden}"><div id="t${i}" class="ptext" style="color:${P[f.fg]};font-size:${poster.size}px;transform:translate(${f.x}px,0) scale(${f.scale})">${upper(poster.text)}</div></div>`;
  const fs = beatFrame(f.beat);
  js.push(`tl.fromTo("#f${i}", {clipPath:"${clipInset[f.wipe][0]}"}, {clipPath:"${clipInset[f.wipe][1]}", duration:${sec(poster.wipeFrames)}, ease:"expo.inOut"}, ${sec(fs)});`);
  if (f.final) {
    js.push(`tl.fromTo("#t${i}", {scale:${f.scale * 1.35}}, {scale:${f.scale}, duration:${sec(10)}, ease:"expo.out", immediateRender:false}, ${sec(fs + poster.wipeFrames)});`);
  }
});
html += `<section id="poster" class="scene clip" data-start="${sec(ps)}" data-duration="${sec(TOTAL - ps)}" data-track-index="0" style="background:${P[poster.fields[0].bg]}">${layers}</section>\n`;

const page = `<!doctype html>
<!-- GENERATED by scripts/build.mjs from content.json. Do not edit by hand. -->
<html lang="en" data-resolution="portrait">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=${CW}, height=${H}" />
<script src="vendor/gsap.min.js"></script>
<style>
@font-face { font-family: "Anton"; src: url("fonts/anton.woff2") format("woff2"); font-weight: 400; }
* { margin: 0; padding: 0; box-sizing: border-box; }
html, body { width: ${CW}px; height: ${H}px; overflow: hidden; background: ${P.black}; }
#root { position: relative; width: 100%; height: 100%; font-family: "${F.family}", sans-serif; }
.scene { position: absolute; left: 0; top: 0; width: ${W}px; height: ${H}px; overflow: hidden; }
.word { position: absolute; left: 0; top: 0; width: ${W}px; height: ${M.anchorY * 2}px; display: flex; align-items: center; justify-content: center; white-space: nowrap; line-height: ${F.lineHeight}; letter-spacing: ${F.tracking}; opacity: 0; transform-origin: 50% 50%; }
.field { position: absolute; left: 0; top: 0; width: ${W}px; height: ${H}px; }
.ptext { position: absolute; left: 0; top: 0; width: ${W}px; height: ${M.anchorY * 2}px; display: flex; align-items: center; justify-content: center; white-space: nowrap; line-height: ${F.lineHeight}; letter-spacing: ${F.tracking}; }
</style>
</head>
<body>
<div id="root" data-composition-id="main" data-start="0" data-duration="${sec(TOTAL)}" data-width="${CW}" data-height="${H}">
${html}</div>
<script>
const tl = gsap.timeline({ paused: true });
${js.join("\n")}
window.__timelines["main"] = tl;
</script>
</body>
</html>
`;
writeFileSync(join(root, "index.html"), page);
console.log(`index.html written: ${TOTAL} frames, ${sec(TOTAL)} s`);
