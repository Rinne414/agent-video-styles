// Generates index.html from content.json + theme. Run: node scripts/build.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { FPS, color, font, win } from "./theme.mjs";
import { makeHighlighter } from "./lib.mjs";
import { hookScene } from "../scenes/hook.mjs";
import { installScene } from "../scenes/install.mjs";
import { editorScene } from "../scenes/editor.mjs";
import { runScene } from "../scenes/run.mjs";
import { outroScene } from "../scenes/outro.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
const content = JSON.parse(read("content.json"));
const { width, height } = content.meta;

// vendor assets so the render needs no network
const copy = (from, to) => {
  fs.mkdirSync(path.dirname(path.join(root, to)), { recursive: true });
  fs.copyFileSync(path.join(root, from), path.join(root, to));
};
copy("node_modules/gsap/dist/gsap.min.js", "vendor/gsap.min.js");
const fonts = [
  ["@fontsource/jetbrains-mono", "jetbrains-mono-latin-400-normal.woff2"],
  ["@fontsource/jetbrains-mono", "jetbrains-mono-latin-700-normal.woff2"],
  ["@fontsource/inter", "inter-latin-600-normal.woff2"],
  ["@fontsource/inter", "inter-latin-800-normal.woff2"],
];
for (const [pkg, file] of fonts) copy(`node_modules/${pkg}/files/${file}`, `assets/fonts/${file}`);

const tokenize = await makeHighlighter(content.meta.theme, ["javascript", "bash"]);

const plan = { tweens: [], classes: [], runs: [], scrolls: [], duration: 0 };
const T = content.timing;
const order = [
  [hookScene, T.hook], [installScene, T.install], [editorScene, T.editor],
  [runScene, T.run], [outroScene, T.outro],
];
let t0 = 0;
let scenes = "";
for (const [build, dur] of order) {
  scenes += build({ content, plan, t0, dur, tokenize }) + "\n";
  t0 += dur;
}
plan.duration = t0;

const vars = {
  W: width, H: height, CODE: font.code, UI: font.ui, CODESIZE: font.codeSize, TERMSIZE: font.termSize,
  WINW: win.w, WINH: win.h, WINLEFT: (width - win.w) / 2, WINTOP: 130, GUTTER: win.gutter, BAR: win.bar,
  CANVAS: color.canvas, LIFT: color.lift, TEXT: color.text, ACCENT: content.colors.accent,
  PROMPT: content.colors.prompt, ADDED: content.colors.added, DANGER: color.danger,
  BAND: color.focusBand, ADDEDBG: color.addedBg, BAR_BG: color.titleBar, BORDER: color.border,
};
const css = read("src/styles.css").replace(/__([A-Z_]+?)__/g, (m, k) => (k in vars ? vars[k] : m));
const runtime = read("src/runtime.js").replace("__PLAN__", () => JSON.stringify(plan)).replace("__FPS__", FPS);

const html = `<!doctype html>
<!-- GENERATED by scripts/build.mjs from content.json. Edit content.json, scenes/ or src/, not this file. -->
<html lang="en"><head>
<meta charset="UTF-8" /><meta name="viewport" content="width=${width}, height=${height}" />
<script src="vendor/gsap.min.js"></script>
<style>${css}</style></head>
<body>
<div id="root" data-composition-id="main" data-start="0" data-duration="${plan.duration}" data-width="${width}" data-height="${height}">
${scenes}
</div>
<script>${runtime}</script>
</body></html>
`;
fs.writeFileSync(path.join(root, "index.html"), html);
console.log(`index.html written: ${plan.duration}s, ${(html.length / 1024).toFixed(0)} KB, ${plan.tweens.length} tweens`);
