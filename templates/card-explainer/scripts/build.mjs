// content.json + assets/audio/timeline.json -> index.html (cards, captions, audio tags)
import { readFileSync, writeFileSync } from "node:fs";
import { charTimes, captionChunks } from "./align.mjs";
import { renderCard } from "./cards.mjs";

const OVERLAP_SEC = 0.2; // next card starts this long before the previous one ends (6 frames)
const AUDIO_LEAD_SEC = 0.25; // narration starts after the card is mostly in
const OUT_SEC = 10 / 30; // card exit duration
const CAPTION_TAIL_SEC = 0.35;

const content = JSON.parse(readFileSync("content.json", "utf8"));
const timeline = JSON.parse(readFileSync("assets/audio/timeline.json", "utf8"));
const { meta, theme, timing } = content;
const padSec = timing.padFrames / timing.fps;
const hexA = (hex, a) => {
  const n = parseInt(hex.slice(1), 16);
  return `rgba(${n >> 16},${(n >> 8) & 255},${n & 255},${a})`;
};

let cursor = 0;
const plan = content.cards.map((card, i) => {
  const seg = timeline.segments.find((s) => s.id === card.id);
  if (!seg) throw new Error(`No timeline segment for ${card.id}; run tts.py first`);
  const audioLen = seg.duration_ms / 1000;
  const isLast = i === content.cards.length - 1;
  const len = audioLen + padSec + (isLast ? timing.outroHoldSec : 0);
  const start = cursor;
  cursor = start + len - (isLast ? 0 : OVERLAP_SEC);
  return { card, seg, i, audioLen, len, start, audioStart: start + AUDIO_LEAD_SEC, isLast };
});
const total = Math.ceil((plan.at(-1).start + plan.at(-1).len) * timing.fps) / timing.fps;
const N = plan.length;
const pad2 = (n) => String(n).padStart(2, "0");

const sections = [];
const caps = [];
const audios = [];
const summary = [];
for (const p of plan) {
  const { card, seg } = p;
  const times = charTimes(card.narration, seg.words);
  const t = (rel) => p.audioStart + rel;
  const body = renderCard(card.layout, { card, meta, times, narration: card.narration, t, audioLen: p.audioLen });
  sections.push(
    `<section id="${card.id}" class="scene clip" data-layout="${card.layout}" data-start="${p.start.toFixed(3)}" data-duration="${p.len.toFixed(3)}" data-track-index="${p.i % 2}">
  <div class="card"><div class="card-inner">${body}</div></div>
  <div class="counter">${pad2(p.i + 1)} / ${pad2(N)}</div>
</section>`,
  );
  const chunks = captionChunks(card.narration, times, seg.words.at(-1).end_ms / 1000 + CAPTION_TAIL_SEC);
  for (const c of chunks) {
    caps.push(`<div class="cap" data-t0="${t(c.t0).toFixed(3)}" data-t1="${t(c.t1).toFixed(3)}">${c.text}</div>`);
  }
  audios.push(
    `<audio id="vo-${card.id}" src="assets/audio/${seg.file}" data-start="${p.audioStart.toFixed(3)}" data-duration="${p.audioLen.toFixed(3)}" data-track-index="3" data-volume="1"></audio>`,
  );
  summary.push({ id: card.id, layout: card.layout, start: +p.start.toFixed(3), len: +p.len.toFixed(3), audioStart: +p.audioStart.toFixed(3), audioLen: +p.audioLen.toFixed(3), captions: chunks.map((c) => `${c.text} [${t(c.t0).toFixed(2)}-${t(c.t1).toFixed(2)}]`) });
}

const ce = { cards: plan.map((p) => ({ id: p.card.id, start: p.start, len: p.len, isLast: p.isLast })), n: N, outSec: OUT_SEC };
const html = `<!doctype html>
<!-- GENERATED by scripts/build.mjs from content.json. Edit content.json, not this file. -->
<html lang="zh-CN"><head>
<meta charset="UTF-8" /><meta name="viewport" content="width=1920, height=1080" />
<style>:root{--bg:${theme.bg};--card:${theme.card};--accent:${theme.accent};--accent-soft:${hexA(theme.accent, 0.16)};--accent-hl:${hexA(theme.accent, 0.35)};--text:${theme.text};--muted:${theme.muted};}</style>
<style>
${readFileSync("src/style.css", "utf8")}</style>
<script src="vendor/gsap.min.js"></script>
</head><body>
<div id="root" data-composition-id="main" data-start="0" data-duration="${total.toFixed(3)}" data-width="1920" data-height="1080">
<div id="progress" class="bar clip" data-start="0" data-duration="${total.toFixed(3)}" data-track-index="4"><div class="bar-fill"></div></div>
${sections.join("\n")}
<div id="captions" class="captions clip" data-start="0" data-duration="${total.toFixed(3)}" data-track-index="5">
${caps.join("\n")}
</div>
${audios.join("\n")}
</div>
<script>window.CE = ${JSON.stringify(ce)};</script>
<script>
${readFileSync("src/main.js", "utf8")}</script>
</body></html>
`;
writeFileSync("index.html", html);
writeFileSync("assets/audio/plan.json", JSON.stringify({ total, cards: summary }, null, 2));
console.log(`index.html: ${N} cards, ${caps.length} captions, ${total.toFixed(2)} s (${Math.round(total * timing.fps)} frames)`);
